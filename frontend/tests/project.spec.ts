import {test,expect} from '@playwright/test';
import {newProject,menuAction,openActions} from './helpers';
test('inline body editing and separate ruby window preserve drafts across navigation and reload',async({page})=>{
  await newProject(page);
  await expect(page.getByRole('button',{name:'サンプルを開く',exact:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'作業バックアップ',exact:true})).toHaveCount(0);
  const body=page.getByLabel('本文を編集',{exact:true});
  await body.fill('吾輩は猫である。名まえはまだない。');
  await page.getByRole('button',{name:'次の段落・文',exact:true}).click();
  await page.getByRole('button',{name:'前の段落・文',exact:true}).click();
  await expect(body).toHaveValue('吾輩は猫である。名まえはまだない。');
  await expect(page.locator('.diff-mirror .diff-changed')).toHaveText('まえ');
  await page.getByRole('button',{name:'更新',exact:true}).click();
  await expect(page.getByLabel('現在の本文',{exact:true})).toContainText('今日は良い天汽');
  await page.getByLabel('前の段落・文',{exact:true}).click();
  await expect(page.getByLabel('現在の本文',{exact:true})).toHaveText('吾輩は猫である。名まえはまだない。');
  await page.getByRole('button',{name:'ルビの訂正',exact:true}).click();
  const ruby=page.getByRole('dialog',{name:'ルビの訂正',exact:true});
  await expect(ruby.getByLabel('本文',{exact:true})).toHaveCount(0);
  await page.getByLabel(/^親文字 /).first().fill('我輩');
  await page.getByRole('button',{name:'ルビ一覧を閉じる',exact:true}).click();
  await page.reload();
  await page.getByRole('button',{name:'ルビの訂正',exact:true}).click();
  await expect(page.getByLabel(/^親文字 /).first()).toHaveValue('我輩');
  await ruby.getByRole('button',{name:'更新',exact:true}).click();
  await expect(page.getByLabel(/^親文字 /).first()).toBeEnabled();
  await page.getByRole('button',{name:'ルビ一覧を閉じる',exact:true}).click();
  await expect(page.getByLabel('現在の本文',{exact:true})).toHaveText('我輩は猫である。名まえはまだない。');
  await page.reload();
  await expect(page.getByLabel('現在の本文',{exact:true})).toHaveText('我輩は猫である。名まえはまだない。');
  await page.getByText('プロジェクト情報',{exact:true}).click();
  await openActions(page);await expect(page.getByRole('button',{name:'作業データを書き出す',exact:true})).toBeVisible();
});
